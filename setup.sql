-- Run in Supabase SQL Editor. Starter schema for Lumora.
create table if not exists public.profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 username text unique not null,
 created_at timestamptz not null default now()
);
create table if not exists public.pins (
 id bigint generated by default as identity primary key,
 title text not null,
 category text not null default 'Other',
 image_url text not null,
 user_id uuid not null references auth.users(id) on delete cascade,
 created_at timestamptz not null default now()
);
create table if not exists public.comments (
 id bigint generated by default as identity primary key,
 pin_id bigint not null references public.pins(id) on delete cascade,
 user_id uuid not null references auth.users(id) on delete cascade,
 body text not null check (char_length(body) between 1 and 500),
 created_at timestamptz not null default now()
);
create table if not exists public.saved_pins (
 user_id uuid not null references auth.users(id) on delete cascade,
 pin_id bigint not null references public.pins(id) on delete cascade,
 created_at timestamptz not null default now(),
 primary key(user_id,pin_id)
);
alter table public.profiles enable row level security;
alter table public.pins enable row level security;
alter table public.comments enable row level security;
alter table public.saved_pins enable row level security;
create policy "Profiles readable" on public.profiles for select to anon,authenticated using(true);
create policy "Users create own profile" on public.profiles for insert to authenticated with check(auth.uid()=id);
create policy "Users update own profile" on public.profiles for update to authenticated using(auth.uid()=id) with check(auth.uid()=id);
create policy "Pins readable" on public.pins for select to anon,authenticated using(true);
create policy "Signed-in users create pins" on public.pins for insert to authenticated with check(auth.uid()=user_id);
create policy "Owners delete pins" on public.pins for delete to authenticated using(auth.uid()=user_id);
create policy "Comments readable" on public.comments for select to anon,authenticated using(true);
create policy "Signed-in users comment as self" on public.comments for insert to authenticated with check(auth.uid()=user_id);
create policy "Users read own saves" on public.saved_pins for select to authenticated using(auth.uid()=user_id);
create policy "Users save for self" on public.saved_pins for insert to authenticated with check(auth.uid()=user_id);
create policy "Users unsave own pins" on public.saved_pins for delete to authenticated using(auth.uid()=user_id);
-- In Supabase Storage, create a PUBLIC bucket named lumora.
create policy "View Lumora images" on storage.objects for select to anon,authenticated using(bucket_id='lumora');
create policy "Upload own Lumora images" on storage.objects for insert to authenticated with check(bucket_id='lumora' and (storage.foldername(name))[1]=auth.uid()::text);

-- Reels: public viewing, authenticated uploads, owner deletion
create table if not exists public.reels (
 id bigint generated by default as identity primary key,
 title text not null check (char_length(title) between 1 and 100),
 video_url text not null,
 user_id uuid not null references auth.users(id) on delete cascade,
 created_at timestamptz not null default now()
);
alter table public.reels enable row level security;
create policy "Reels readable by everyone" on public.reels for select to anon,authenticated using(true);
create policy "Signed-in users publish own reels" on public.reels for insert to authenticated with check(auth.uid()=user_id);
create policy "Owners delete own reels" on public.reels for delete to authenticated using(auth.uid()=user_id);
create policy "View Lumora reels" on storage.objects for select to anon,authenticated using(bucket_id='lumora-reels');
create policy "Upload own Lumora reels" on storage.objects for insert to authenticated with check(bucket_id='lumora-reels' and (storage.foldername(name))[1]=auth.uid()::text);
create policy "Delete own Lumora reels" on storage.objects for delete to authenticated using(bucket_id='lumora-reels' and (storage.foldername(name))[1]=auth.uid()::text);
